function build(table) {
  const out = {}
  for (const [code, values] of Object.entries(table)) {
    if (values.length !== SHELL_KEYS.length) {
      throw new Error(`shell-copy.${code} has ${values.length} of ${SHELL_KEYS.length} strings`)
    }
    out[code] = Object.fromEntries(SHELL_KEYS.map((key, i) => [key, values[i]]))
  }
  return out
}

export const shellCopy = build(rows)
