function build(table) {
  const out = {}
  for (const [code, values] of Object.entries(table)) {
    if (values.length !== TRY_KEYS.length) {
      throw new Error(`try-copy.${code} has ${values.length} of ${TRY_KEYS.length} strings`)
    }
    out[code] = Object.fromEntries(TRY_KEYS.map((key, i) => [key, values[i]]))
  }
  return out
}

export const tryCopy = build(rows)
