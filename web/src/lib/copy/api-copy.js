function build(table) {
  const out = {}
  for (const [code, values] of Object.entries(table)) {
    if (values.length !== API_KEYS.length) {
      throw new Error(`api-copy.${code} has ${values.length} of ${API_KEYS.length} strings`)
    }
    out[code] = Object.fromEntries(API_KEYS.map((key, i) => [key, values[i]]))
  }
  return out
}

