function build(table) {
  const out = {}
  for (const [code, values] of Object.entries(table)) {
    if (values.length !== GRAPH_KEYS.length) {
      throw new Error(`graph-copy.${code} has ${values.length} of ${GRAPH_KEYS.length} strings`)
    }
    out[code] = Object.fromEntries(GRAPH_KEYS.map((key, i) => [key, values[i]]))
  }
  return out
}

export const graphCopy = build(rows)
